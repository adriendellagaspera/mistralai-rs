"""Generate the idiomatic SDK facade from generated raw Rust bindings.

The semantic manifest controls stable public naming. Request setters and raw
operation contracts are derived from openapi-to-rust output, so regeneration
tracks compatible additions and fails closed on unsupported structural drift.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
import re


GENERATED = "// @generated by codegen/sdk_facade.py; do not edit by hand.\n"


def _balanced_body(source: str, marker: str) -> str:
    start = source.find(marker)
    if start < 0:
        raise ValueError(f"raw Rust item not found: {marker}")
    opening = source.find("{", start + len(marker))
    if opening < 0:
        raise ValueError(f"raw Rust item has no body: {marker}")
    depth = 0
    for index in range(opening, len(source)):
        char = source[index]
        if char == "{":
            depth += 1
        elif char == "}":
            depth -= 1
            if depth == 0:
                return source[opening + 1:index]
    raise ValueError(f"unterminated raw Rust item: {marker}")


def struct_fields(source: str, name: str) -> dict[str, str]:
    body = _balanced_body(source, f"pub struct {name}")
    fields = {}
    field_pattern = re.compile(r"(?m)^\s*pub (r#)?([A-Za-z0-9_]+):\s*")
    pairs = {">": "<", ")": "(", "]": "[", "}": "{"}
    for match in field_pattern.finditer(body):
        stack = []
        end = None
        for index in range(match.end(), len(body)):
            char = body[index]
            if char in "<([{":
                stack.append(char)
            elif char in pairs:
                if not stack or stack.pop() != pairs[char]:
                    raise ValueError(f"unbalanced field type in raw type {name}")
            elif char == "," and not stack:
                end = index
                break
        if end is None:
            raise ValueError(f"unterminated public field in raw type {name}")
        fields[(match.group(1) or "") + match.group(2)] = body[match.end():end].strip()
    if not fields:
        raise ValueError(f"no public fields parsed for raw type {name}")
    return fields


def require_type(source: str, name: str) -> None:
    if not re.search(rf"(?m)^pub (?:struct|enum) {re.escape(name)}\b", source):
        raise ValueError(f"raw Rust type not found: {name}")


def require_operation(source: str, name: str, request_type: str) -> None:
    pattern = rf"pub async fn {re.escape(name)}\s*\(\s*&self,\s*request: {re.escape(request_type)},"
    if not re.search(pattern, source):
        raise ValueError(
            f"raw operation {name} no longer accepts {request_type}; semantic review required"
        )


def _option_inner(rust_type: str) -> tuple[str, bool] | None:
    if not rust_type.startswith("Option<") or not rust_type.endswith(">"):
        return None
    inner = rust_type[7:-1]
    if inner.startswith("Option<") and inner.endswith(">"):
        return inner[7:-1], True
    return inner, False


def _argument(name: str, rust_type: str) -> tuple[str, str]:
    if rust_type == "String":
        return f"{name}: impl Into<String>", f"{name}.into()"
    return f"{name}: {rust_type}", name


def request_setters(fields: dict[str, str], reserved: set[str]) -> str:
    methods = []
    for raw_name, rust_type in fields.items():
        name = raw_name.removeprefix("r#")
        if name in reserved:
            continue
        optional = _option_inner(rust_type)
        if optional is None:
            raise ValueError(
                f"new required request field {raw_name}: {rust_type}; semantic review required"
            )
        inner, nullable = optional
        argument, value = _argument(name, inner)
        wrapped = f"Some(Some({value}))" if nullable else f"Some({value})"
        signature = f"    pub fn {name}(mut self, {argument}) -> Self {{"
        if len(signature) > 100:
            signature = (
                f"    pub fn {name}(\n"
                f"        mut self,\n"
                f"        {argument},\n"
                "    ) -> Self {"
            )
        methods.append(f"""
    #[must_use]
{signature}
        self.raw.{raw_name} = {wrapped};
        self
    }}
""")
        if nullable:
            methods.append(f"""
    #[must_use]
    pub fn {name}_null(mut self) -> Self {{
        self.raw.{raw_name} = Some(None);
        self
    }}
""")
    return "".join(methods)


