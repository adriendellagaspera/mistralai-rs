def generate(raw: Path, target: Path, manifest_path: Path) -> None:
    manifest = json.loads(manifest_path.read_text())
    if manifest.get("schema_version") != 1:
        raise ValueError("unsupported SDK semantic manifest version")
    types = (raw / "types.rs").read_text()
    client = (raw / "client.rs").read_text()
    chat = manifest["resources"]["chat"]
    ocr = manifest["resources"]["ocr"]

    for config in (chat, ocr):
        for key in ("request_type", "response_type"):
            require_type(types, config[key])
    require_type(types, chat["stream_item_type"])
    require_operation(client, chat["complete_operation"], chat["request_type"])
    require_operation(client, chat["stream_operation"], chat["request_type"])
    require_operation(client, ocr["operation"], ocr["request_type"])

    chat_fields = struct_fields(types, chat["request_type"])
    ocr_fields = struct_fields(types, ocr["request_type"])
    target.mkdir(parents=True, exist_ok=True)
    (target / "chat.rs").write_text(generate_chat(chat, chat_fields))
    (target / "ocr.rs").write_text(generate_ocr(ocr, ocr_fields))
    (target / "mod.rs").write_text(generate_mod(chat, ocr))
    coverage = {
        "schema_version": 1,
        "resources": {
            "chat": {
                "operations": [chat["complete_operation"], chat["stream_operation"]],
                "request_fields": sorted(chat_fields),
            },
            "ocr": {
                "operations": [ocr["operation"]],
                "request_fields": sorted(ocr_fields),
            },
        },
    }
    (target / "coverage.json").write_text(json.dumps(coverage, indent=2) + "\n")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("raw", type=Path)
    parser.add_argument("target", type=Path)
    parser.add_argument("--manifest", type=Path, required=True)
    args = parser.parse_args()
    generate(args.raw, args.target, args.manifest)


if __name__ == "__main__":
    main()
