"""SDK publication requires complete coverage and exact public facade parity."""

import unittest
from collections import Counter
from pathlib import Path

from build import require_publish_parity


class PublishParityTests(unittest.TestCase):
    def test_generated_facade_has_current_provenance_marker(self):
        facade = Path(__file__).resolve().parents[1] / "src" / "sdk"
        generated = sorted(path for path in facade.glob("*.rs") if path.name != "error.rs")
        self.assertTrue(generated)
        for path in generated:
            with self.subTest(path=path.name):
                self.assertTrue(
                    path.read_text().startswith(
                        "// @generated by rust-sdk-generator via sdk-build; do not edit by hand.\n"
                    )
                )

    def test_zero_rejections_and_identical_committed_facade_pass(self):
        require_publish_parity(Counter({"derived": 169, "overridden": 4}), [])

    def test_full_coverage_is_not_equivalent_to_public_facade_parity(self):
        with self.assertRaisesRegex(ValueError, "committed public baseline in 2 files"):
            require_publish_parity(
                Counter({"derived": 169, "overridden": 4}),
                ["client.rs", "models.rs"],
            )

    def test_identical_facade_does_not_hide_missing_operations(self):
        with self.assertRaisesRegex(ValueError, "1 OpenAPI operations remain rejected"):
            require_publish_parity(
                Counter({"derived": 168, "overridden": 4, "rejected": 1}),
                [],
            )


if __name__ == "__main__":
    unittest.main()
