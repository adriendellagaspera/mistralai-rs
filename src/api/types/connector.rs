pub use crate::prelude::*;

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
#[serde(tag = "protocol")]
#[non_exhaustive]
pub enum Connector {
    #[serde(rename = "http")]
    #[non_exhaustive]
    Http {
        #[serde(skip_serializing_if = "Option::is_none")]
        blocked_by: Option<Vec<ConsumerType>>,
        #[serde(skip_serializing_if = "Option::is_none")]
        connection_config: Option<PublicConnectionConfig>,
        #[serde(skip_serializing_if = "Option::is_none")]
        connection_credentials: Option<Vec<AuthenticationConfiguration>>,
        #[serde(skip_serializing_if = "Option::is_none")]
        connection_preferences: Option<Vec<ConnectionPreference>>,
        #[serde(default)]
        #[serde(with = "crate::core::flexible_datetime::offset")]
        created_at: DateTime<FixedOffset>,
        #[serde(skip_serializing_if = "Option::is_none")]
        creator_id: Option<String>,
        #[serde(default)]
        description: String,
        #[serde(skip_serializing_if = "Option::is_none")]
        execution_env: Option<PublicExecutionEnv>,
        #[serde(skip_serializing_if = "Option::is_none")]
        icon_url: Option<String>,
        #[serde(default)]
        id: String,
        #[serde(skip_serializing_if = "Option::is_none")]
        is_authenticated: Option<bool>,
        #[serde(skip_serializing_if = "Option::is_none")]
        locale: Option<ConnectorLocale>,
        #[serde(skip_serializing_if = "Option::is_none")]
        mistral: Option<bool>,
        #[serde(default)]
        #[serde(with = "crate::core::flexible_datetime::offset")]
        modified_at: DateTime<FixedOffset>,
        #[serde(default)]
        name: String,
        #[serde(skip_serializing_if = "Option::is_none")]
        owner_id: Option<String>,
        owner_type: ConsumerType,
        #[serde(default)]
        private_tool_execution: bool,
        #[serde(skip_serializing_if = "Option::is_none")]
        server: Option<String>,
        #[serde(skip_serializing_if = "Option::is_none")]
        server_card: Option<McpServerCard>,
        #[serde(skip_serializing_if = "Option::is_none")]
        supported_auth_methods: Option<Vec<PublicAuthenticationMethod>>,
        #[serde(default)]
        supports_mcp: bool,
        #[serde(skip_serializing_if = "Option::is_none")]
        system_prompt: Option<String>,
        #[serde(skip_serializing_if = "Option::is_none")]
        title: Option<String>,
        #[serde(skip_serializing_if = "Option::is_none")]
        tools: Option<Vec<ConnectorTool>>,
        visibility: ResourceVisibility,
    },

    #[serde(rename = "mcp")]
    #[non_exhaustive]
    Mcp {
        #[serde(skip_serializing_if = "Option::is_none")]
        blocked_by: Option<Vec<ConsumerType>>,
        #[serde(skip_serializing_if = "Option::is_none")]
        connection_config: Option<PublicConnectionConfig>,
        #[serde(skip_serializing_if = "Option::is_none")]
        connection_credentials: Option<Vec<AuthenticationConfiguration>>,
        #[serde(skip_serializing_if = "Option::is_none")]
        connection_preferences: Option<Vec<ConnectionPreference>>,
        #[serde(default)]
        #[serde(with = "crate::core::flexible_datetime::offset")]
        created_at: DateTime<FixedOffset>,
        #[serde(skip_serializing_if = "Option::is_none")]
        creator_id: Option<String>,
        #[serde(default)]
        description: String,
        #[serde(skip_serializing_if = "Option::is_none")]
        execution_env: Option<PublicExecutionEnv>,
        #[serde(skip_serializing_if = "Option::is_none")]
        icon_url: Option<String>,
        #[serde(default)]
        id: String,
        #[serde(skip_serializing_if = "Option::is_none")]
        is_authenticated: Option<bool>,
        #[serde(skip_serializing_if = "Option::is_none")]
        locale: Option<ConnectorLocale>,
        #[serde(skip_serializing_if = "Option::is_none")]
        mistral: Option<bool>,
        #[serde(default)]
        #[serde(with = "crate::core::flexible_datetime::offset")]
        modified_at: DateTime<FixedOffset>,
        #[serde(default)]
        name: String,
        #[serde(skip_serializing_if = "Option::is_none")]
        owner_id: Option<String>,
        owner_type: ConsumerType,
        #[serde(default)]
        private_tool_execution: bool,
        #[serde(skip_serializing_if = "Option::is_none")]
        server: Option<String>,
        #[serde(skip_serializing_if = "Option::is_none")]
        server_card: Option<McpServerCard>,
        #[serde(skip_serializing_if = "Option::is_none")]
        supported_auth_methods: Option<Vec<PublicAuthenticationMethod>>,
        #[serde(default)]
        supports_mcp: bool,
        #[serde(skip_serializing_if = "Option::is_none")]
        system_prompt: Option<String>,
        #[serde(skip_serializing_if = "Option::is_none")]
        title: Option<String>,
        #[serde(skip_serializing_if = "Option::is_none")]
        tools: Option<Vec<ConnectorTool>>,
        visibility: ResourceVisibility,
    },

    /// Catch-all variant for unrecognized discriminant values.
    /// If the server sends a discriminant not recognized by the current SDK
    /// version, the raw payload is captured here so callers can still inspect it.
    #[serde(untagged)]
    __Unknown(serde_json::Value),
}

