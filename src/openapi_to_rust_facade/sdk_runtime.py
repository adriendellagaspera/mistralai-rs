"""Explicit Rust runtime contract used by deterministic facade emission."""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class RustFacadeRuntime:
    """Consumer-owned support paths referenced by generated facade code.

    The compiler owns the facade shape, while the embedding SDK owns stable error
    and streaming support. Keeping those names explicit prevents a raw-binding
    backend from leaking runtime assumptions into the compiler.
    """

    error_type: str = "SdkError"
    error_module: str = "error"
    error_exports: tuple[str, ...] = (
        "ApiError",
        "SdkError",
        "TransportError",
        "TransportErrorKind",
    )
    sse_json_events: str = "crate::streaming::json_events"
    generated_marker: str = (
        "// @generated by openapi-to-rust-facade; do not edit by hand.\n"
    )


DEFAULT_RUNTIME = RustFacadeRuntime()
